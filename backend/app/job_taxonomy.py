def skills_for_sector(key: str) -> list[str]:
    """Skills for one sector, falling back to an alias or the full list."""
    if not key:
        return ALL_SKILLS
    return SKILLS_BY_SECTOR.get(key) or SKILLS_BY_SECTOR.get(SKILL_ALIASES.get(key, ""), []) or ALL_SKILLS


